// Helper functions for product search
export function searchProducts(query) {
  if (!query || query.trim() === '') {
    return products;
  }

  const searchTerm = query.toLowerCase();
  return products.filter(product => {
    return (
      product.name.toLowerCase().includes(searchTerm) ||
      product.description.toLowerCase().includes(searchTerm) ||
      product.category.toLowerCase().includes(searchTerm) ||
      product.features.some(feature => feature.toLowerCase().includes(searchTerm))
    );
  });
}

export function searchByCategory(category) {
  return products.filter(product =>
    product.category.toLowerCase() === category.toLowerCase()
  );
}

export function searchByPriceRange(minPrice, maxPrice) {
  return products.filter(product =>
    product.price >= minPrice && product.price <= maxPrice
  );
}

export function getProductById(productId) {
  return products.find(product => product.id === productId);
}

export function getInStockProducts() {
  return products.filter(product => product.stock > 0);
}

export function getBestRatedProducts(minRating = 4.5) {
  return products.filter(product => product.rating >= minRating);
}

export function getCheapestProducts(limit = 5) {
  return [...products].sort((a, b) => a.price - b.price).slice(0, limit);
}

export function getMostExpensiveProducts(limit = 5) {
  return [...products].sort((a, b) => b.price - a.price).slice(0, limit);
}
